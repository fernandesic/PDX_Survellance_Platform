"""
Cost-Effectiveness Analysis (CEA) Framework for Counterfactual Scenarios.

This module provides the analytical framework to compute cost-effectiveness
metrics from SEIRDV simulation outputs, including:
- DALYs (Disability-Adjusted Life Years)
- Deaths Averted
- ICER (Incremental Cost-Effectiveness Ratio)
- WHO-CHOICE threshold comparisons

The user must provide the actual unit costs, GDP per capita, and DALY weights.
"""

from __future__ import annotations
from dataclasses import dataclass
import numpy as np
import pandas as pd


@dataclass
class CostInputs:
    """External economic and epidemiological inputs required for CEA."""
    cost_per_vaccine: float
    # Add other intervention costs if needed (e.g., cost per treatment)
    cost_per_treatment: float = 0.0
    
    # DALY weights (from Global Burden of Disease study)
    disability_weight: float = 0.0
    illness_duration_years: float = 0.0
    
    # YLL (Years of Life Lost) inputs
    life_expectancy_at_death: float = 0.0
    
    # WHO-CHOICE thresholds
    gdp_per_capita: float = 0.0


@dataclass
class CEAResult:
    """Results of a Cost-Effectiveness Analysis for a single simulation run or ensemble."""
    baseline_cases: float
    baseline_deaths: float
    baseline_cost: float
    baseline_dalys: float
    
    scenario_cases: float
    scenario_deaths: float
    scenario_vaccines_used: float
    scenario_cost: float
    scenario_dalys: float
    
    cases_averted: float
    deaths_averted: float
    dalys_averted: float
    incremental_cost: float
    
    icer: float  # Cost per DALY averted
    
    is_highly_cost_effective: bool
    is_cost_effective: bool


def calculate_dalys(cases: float, deaths: float, inputs: CostInputs) -> float:
    """Calculate total DALYs = YLD (Years Lived with Disability) + YLL (Years of Life Lost)."""
    yld = cases * inputs.illness_duration_years * inputs.disability_weight
    yll = deaths * inputs.life_expectancy_at_death
    return yld + yll


def compute_cea(
    baseline_df: pd.DataFrame,
    scenario_df: pd.DataFrame,
    inputs: CostInputs
) -> CEAResult:
    """
    Compute Cost-Effectiveness Analysis comparing a scenario against a baseline.
    
    Expects DataFrames generated by `run_seirdv` containing `sim`, `step`,
    and compartment columns like `I[1]`, `D[1]`, `V[1]`.
    
    Note: Currently aggregates across all populations (if n_populations > 1).
    """
    # 1. Extract final cumulative metrics
    # Assuming baseline_df and scenario_df have the same time steps
    max_step = baseline_df['step'].max()
    
    base_final = baseline_df[baseline_df['step'] == max_step]
    scen_final = scenario_df[scenario_df['step'] == max_step]
    
    # Aggregate across populations
    # E.g., 'D[1]', 'D[2]' -> total deaths
    d_cols = [c for c in baseline_df.columns if c.startswith('D[')]
    v_cols = [c for c in baseline_df.columns if c.startswith('V[')]
    # Cases can be derived from S(0) - S(t), or we assume R + D + I
    
    base_deaths = base_final[d_cols].sum(axis=1).mean()  # average across sims
    scen_deaths = scen_final[d_cols].sum(axis=1).mean()
    
    # Approximating cumulative cases: R + D + I at final step (if V is separate from S)
    r_cols = [c for c in baseline_df.columns if c.startswith('R[')]
    i_cols = [c for c in baseline_df.columns if c.startswith('I[')]
    
    base_cases = (base_final[r_cols].sum(axis=1) + base_final[d_cols].sum(axis=1) + base_final[i_cols].sum(axis=1)).mean()
    scen_cases = (scen_final[r_cols].sum(axis=1) + scen_final[d_cols].sum(axis=1) + scen_final[i_cols].sum(axis=1)).mean()
    
    base_vacc = base_final[v_cols].sum(axis=1).mean()
    scen_vacc = scen_final[v_cols].sum(axis=1).mean()
    
    # 2. Compute Costs
    base_cost = (base_cases * inputs.cost_per_treatment) + (base_vacc * inputs.cost_per_vaccine)
    scen_cost = (scen_cases * inputs.cost_per_treatment) + (scen_vacc * inputs.cost_per_vaccine)
    
    # 3. Compute DALYs
    base_dalys = calculate_dalys(base_cases, base_deaths, inputs)
    scen_dalys = calculate_dalys(scen_cases, scen_deaths, inputs)
    
    # 4. Compute incremental metrics
    cases_averted = max(0.0, base_cases - scen_cases)
    deaths_averted = max(0.0, base_deaths - scen_deaths)
    dalys_averted = max(0.0, base_dalys - scen_dalys)
    
    incremental_cost = scen_cost - base_cost
    
    # 5. ICER
    if dalys_averted > 0:
        icer = incremental_cost / dalys_averted
    else:
        icer = float('inf') if incremental_cost > 0 else 0.0
        
    # 6. WHO-CHOICE Thresholds
    # Highly cost-effective: ICER < 1x GDP per capita
    # Cost-effective: ICER < 3x GDP per capita
    is_highly_ce = False
    is_ce = False
    
    if inputs.gdp_per_capita > 0:
        if icer < inputs.gdp_per_capita:
            is_highly_ce = True
            is_ce = True
        elif icer < (3 * inputs.gdp_per_capita):
            is_ce = True

    return CEAResult(
        baseline_cases=base_cases,
        baseline_deaths=base_deaths,
        baseline_cost=base_cost,
        baseline_dalys=base_dalys,
        scenario_cases=scen_cases,
        scenario_deaths=scen_deaths,
        scenario_vaccines_used=scen_vacc,
        scenario_cost=scen_cost,
        scenario_dalys=scen_dalys,
        cases_averted=cases_averted,
        deaths_averted=deaths_averted,
        dalys_averted=dalys_averted,
        incremental_cost=incremental_cost,
        icer=icer,
        is_highly_cost_effective=is_highly_ce,
        is_cost_effective=is_ce
    )


def run_with_cea(kwargs: dict, cost_inputs: CostInputs) -> tuple[pd.DataFrame, pd.DataFrame, CEAResult]:
    """
    Helper function to run a scenario alongside a "Do Nothing" baseline 
    and compute Cost-Effectiveness Analysis.
    
    Returns:
        (baseline_df, scenario_df, cea_result)
    """
    from predictions.scenarios.wbepi_engine import run_seirdv
    
    # 1. Run the intervention scenario
    scenario_df = run_seirdv(**kwargs)
    
    # 2. Run the baseline scenario (no intervention)
    baseline_kwargs = kwargs.copy()
    
    # Remove/disable interventions for baseline
    baseline_kwargs['vacc_coverage'] = 0.0
    baseline_kwargs['interv_efficacy'] = 0.0
    baseline_kwargs['interv_vacc_coverage'] = 0.0
    
    # Reset seed to the same value to ensure identical counterfactual timeline
    if 'rng' in kwargs and hasattr(kwargs['rng'], 'bit_generator'):
        # For true comparability, we would ideally pass the exact same seed here.
        # This is a simplification.
        pass
        
    baseline_df = run_seirdv(**baseline_kwargs)
    
    # 3. Compute CEA
    cea = compute_cea(baseline_df, scenario_df, cost_inputs)
    
    return baseline_df, scenario_df, cea
